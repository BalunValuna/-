const LANGS = ['ru', 'en'];

export function lang() {
  return settings.get('language') === 'en' ? 'en' : 'ru';
}

export function t(key, ...args) {
  const entry = STRINGS[key];
  let s = entry ? entry[LANGS.indexOf(lang())] ?? entry[0] : key;
  args.forEach((a, i) => (s = s.replace(`{${i}}`, a)));
  return s;
}

/** Inline pair for content strings defined next to game data: tr(['рус', 'eng']). */
export function tr(pair) {
  if (!Array.isArray(pair)) return pair;
  return lang() === 'en' ? pair[1] ?? pair[0] : pair[0];
}
